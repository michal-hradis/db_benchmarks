import argparse
import json
import logging
import random
from pathlib import Path

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

def parse_args():
    parser = argparse.ArgumentParser(
        description="Prepares a batch for title generation to be sumbitted to OpenAI API from a jsonl chunk file with included queries. "
                    "Picks random queries, random prompts and random models for each chunk. "
                    "The chunk file contains 'id' and 'text' fields. The 'id' should be used as 'custom_id' in the OpenAI API call. "
                    'Two messages should be generated per each (chunk, query) pair: system and user message. '
                    'The system message is a copy of the prompt text file content. '
                    "The user message is generated by filling in the prompt template with the 'chunk' text and the 'query'. "
                    "Queries are stored in as lists of string in fields specified in cmd arguments. "
                    "Prompts are stored as text files a in a specified directory. "
                    "Can skip chunks based on 'true' value of specified keys.")
    parser.add_argument("--chunk-file", required=True, help="Path to the input jsonl file with text chunks.")
    parser.add_argument("--output-file-prefix", required=True, help="Path to save the output jsonl batch files - suffix is model name.")
    parser.add_argument("--query-fields", nargs='+', default=["factual_search_queries", "factual_question_queries", "exploratory_research_queries"],
                        help="List of fields in the chunk file that contain lists of queries to choose from.")
    parser.add_argument("--prompt-dir", required=True, help="Path to the directory containing prompt text files.")
    parser.add_argument("--models", nargs='+',
                        default=["gpt-5", "gpt-5-mini", "gpt-5-nano", "gpt-4.1", "gpt-4.1-mini", "gpt-4.1-nano",
                                 "gpt-4o-mini", "gpt-4o", "gpt-4-turbo", "gpt-3.5-turbo"],
                        help="List of OpenAI models to choose from.")
    parser.add_argument("--skip-if-true", nargs='*', default=["incomprehensible", "all_context_missing"],
                        help="List of fields in the chunk file. If any of these fields has a 'true' value, the chunk is skipped.")
    parser.add_argument('--queries-per-chunk', type=int, default=1, help="Number of queries to select per chunk.")
    parser.add_argument('--model-prompt-combinations', type=int, default=2, help="Number of (model, prompt) combinations to create per each query-chunk pair.")
    parser.add_argument('--template', type=str, default="query: {query}\nretrieved text chunk: {chunk}\n",
                        help="Template for the user message, with placeholders {query} and {chunk}.")
    return parser.parse_args()

def load_prompts(prompt_dir):
    """Load all prompt files from the directory."""
    prompt_path = Path(prompt_dir)
    prompts = {}

    for prompt_file in prompt_path.glob("*.txt"):
        with open(prompt_file, 'r', encoding='utf-8') as f:
            prompts[prompt_file.stem] = f.read()

    logging.info(f"Loaded {len(prompts)} prompts from {prompt_dir}")
    return prompts

def should_skip_chunk(chunk, skip_fields):
    """Check if chunk should be skipped based on skip_fields."""
    for field in skip_fields:
        if field in chunk and chunk[field] is True:
            return True
    return False

def get_queries_from_chunk(chunk, query_fields):
    """Extract all available queries from the chunk."""
    all_queries = []
    for field in query_fields:
        if field in chunk and isinstance(chunk[field], list):
            all_queries.extend(chunk[field])
    return all_queries

def create_batch_request(custom_id, model, system_message, user_message):
    """Create an OpenAI batch API request."""
    return {
        "custom_id": custom_id,
        "method": "POST",
        "url": "/v1/chat/completions",
        "body": {
            "model": model,
            "messages": [
                {"role": "system", "content": system_message},
                {"role": "user", "content": user_message}
            ]
        }
    }

def generate_batch(chunk_file, query_fields, prompts, models, skip_fields,
                   queries_per_chunk, model_prompt_combinations, template):
    """Generate batch requests for OpenAI API."""
    batch_requests = []
    chunks_processed = 0
    chunks_skipped = 0

    prompt_names = list(prompts.keys())

    with open(chunk_file, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            if not line.strip():
                continue

            chunk = json.loads(line)

            # Skip if conditions met
            if should_skip_chunk(chunk, skip_fields):
                chunks_skipped += 1
                continue

            # Get required fields
            if 'id' not in chunk or 'text' not in chunk:
                logging.warning(f"Line {line_num}: Missing 'id' or 'text' field, skipping")
                continue

            chunk_id = chunk['id']
            chunk_text = chunk['text']

            # Get available queries
            available_queries = get_queries_from_chunk(chunk, query_fields)
            if not available_queries:
                logging.warning(f"Chunk {chunk_id}: No queries found, skipping")
                continue

            # Select random queries
            num_queries = min(queries_per_chunk, len(available_queries))
            selected_queries = random.sample(available_queries, num_queries)

            # For each selected query
            for query_idx, query in enumerate(selected_queries):
                # Create multiple (model, prompt) combinations
                for combo_idx in range(model_prompt_combinations):
                    # Randomly select model and prompt
                    model = random.choice(models)
                    prompt_name = random.choice(prompt_names)
                    system_message = prompts[prompt_name]

                    # Generate user message from template
                    user_message = template.format(query=query, chunk=chunk_text)

                    # Create unique custom_id
                    custom_id = f"{chunk_id}_q{query_idx}_p{combo_idx}"

                    # Create batch request
                    request = create_batch_request(custom_id, model, system_message, user_message)
                    batch_requests.append(request)

            chunks_processed += 1

    logging.info(f"Processed {chunks_processed} chunks, skipped {chunks_skipped} chunks")
    logging.info(f"Generated {len(batch_requests)} batch requests")

    return batch_requests

def save_batch(batch_requests, output_file_prefix):
    """Save batch requests to JSONL files following the template f'{output_file_prefix}{model_name}.jsonl'."""

    # Group requests by model
    requests_by_model = {}
    for request in batch_requests:
        model = request['body']['model']
        if model not in requests_by_model:
            requests_by_model[model] = []
        requests_by_model[model].append(request)

    # Save each model's requests to a separate file
    for model, requests in requests_by_model.items():
        output_file = f"{output_file_prefix}{model}.jsonl"
        Path(output_file).parent.mkdir(parents=True, exist_ok=True)

        with open(output_file, 'w', encoding='utf-8') as f:
            for request in requests:
                f.write(json.dumps(request, ensure_ascii=False) + '\n')

        logging.info(f"Saved {len(requests)} requests to {output_file}")

    logging.info(f"Total: {len(batch_requests)} requests across {len(requests_by_model)} models")

def main():
    args = parse_args()

    # Load prompts
    prompts = load_prompts(args.prompt_dir)
    if not prompts:
        logging.error(f"No prompts found in {args.prompt_dir}")
        return

    # Generate batch
    batch_requests = generate_batch(
        args.chunk_file,
        args.query_fields,
        prompts,
        args.models,
        args.skip_if_true,
        args.queries_per_chunk,
        args.model_prompt_combinations,
        args.template
    )

    # Save batch
    save_batch(batch_requests, args.output_file_prefix)

    logging.info("Batch generation completed successfully")

if __name__ == "__main__":
    main()
